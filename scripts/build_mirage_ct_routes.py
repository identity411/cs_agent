"""Compile manifest-paired, user-recorded Mirage CT Walklab routes."""

import argparse
import base64
import hashlib
import json
import math
import zlib
from pathlib import Path

from scripts.build_r3_replays import KEY_BITS


def _recording(path, map_id, map_hash):
    raw = path.read_bytes()
    data = json.loads(raw)
    if (data.get("format") != "walklab-v2"
            or data.get("mapId") != map_id
            or data.get("mapHash") != map_hash
            or data.get("hz") != 20 or data.get("side") != "defend"):
        raise ValueError(f"invalid CT recording identity: {path.name}")
    rows = []
    for tick, frame in enumerate(data.get("frames", ())):
        if frame.get("tick") != tick:
            raise ValueError(f"noncontiguous ticks: {path.name}")
        values = [*(frame.get("position") or ()), frame.get("yaw"),
                  frame.get("pitch")]
        if (len(values) != 5
                or any(not isinstance(v, (int, float)) or not math.isfinite(v)
                       for v in values)):
            raise ValueError(f"invalid pose: {path.name}")
        keys = frame.get("keys")
        if not isinstance(keys, list) or any(key not in KEY_BITS for key in keys):
            raise ValueError(f"invalid keys: {path.name}")
        rows.append(tuple(round(v, 4) for v in values)
                    + (sum(KEY_BITS[key] for key in set(keys)),))
    if len(rows) < 2:
        raise ValueError(f"too few frames: {path.name}")
    return tuple(rows), hashlib.sha256(raw).hexdigest()


def compile_manifest(manifest_path, static_map):
    manifest = json.loads(manifest_path.read_text())
    map_data = static_map["map"]
    map_id, map_hash = manifest["mapId"], manifest["mapHash"]
    if (map_id != map_data["id"] or map_hash != map_data["geometry_hash"]):
        raise ValueError("Mirage fixture hash mismatch")
    seen = set()

    def read(name):
        if name in seen or Path(name).name != name:
            raise ValueError(f"duplicate or unsafe source: {name}")
        seen.add(name)
        return _recording(manifest_path.parent / name, map_id, map_hash)

    pairs = []
    for item in manifest["pairs"]:
        opening, open_sha = read(item["opening"])
        hold, hold_sha = read(item["hold"])
        if (item["site"] not in ("A", "B")
                or math.dist(opening[-1][:3], hold[0][:3]) > 0.2
                or math.dist(hold[-1][:3], hold[0][:3]) > 1.0):
            raise ValueError(f"disconnected CT pair: {item['name']}")
        pairs.append({"name": item["name"], "site": item["site"],
                      "opening": opening, "hold": hold,
                      "sha256": {"opening": open_sha, "hold": hold_sha}})
    retakes = {"B_to_A": []}
    for item in manifest["retakes"]:
        frames, sha = read(item["source"])
        if item["origin"] != "B" or item["target"] != "A":
            raise ValueError("unsupported retake direction")
        retakes["B_to_A"].append({"name": item["name"],
                                   "frames": frames, "sha256": sha})
    if len(pairs) != 6 or len(retakes["B_to_A"]) != 2:
        raise ValueError("incomplete Mirage CT manifest")
    return {"map_id": map_id, "map_hash": map_hash,
            "pairs": pairs, "retakes": retakes}


def _encode_frames(frames):
    raw = json.dumps([list(frame) for frame in frames],
                     separators=(",", ":")).encode("ascii")
    return base64.b85encode(zlib.compress(raw, 9)).decode("ascii")


def _payload_lines(payload, indent):
    return [f'{indent}"{payload[i:i + 96]}"'
            for i in range(0, len(payload), 96)]


def write_module(compiled, output):
    lines = ['"""User-recorded Mirage CT routes; generated by build_mirage_ct_routes.py."""',
             "import base64",
             "import json",
             "import zlib",
             "",
             "",
             "def _frames(payload):",
             "    data = zlib.decompress(base64.b85decode(payload))",
             "    return tuple(tuple(row) for row in json.loads(data))",
             "",
             "",
             f"MAP_ID = {compiled['map_id']!r}",
             f"MAP_HASH = {compiled['map_hash']!r}", "PAIRS = ("]
    for pair in compiled["pairs"]:
        lines.append("    {")
        for key in ("name", "site", "sha256"):
            lines.append(f"        {key!r}: {pair[key]!r},")
        for key in ("opening", "hold"):
            lines.append(f"        {key!r}: _frames(")
            lines.extend(_payload_lines(_encode_frames(pair[key]), "            "))
            lines.append("        ),")
        lines.append("    },")
    lines.extend((")", "RETAKES = {", "    'B_to_A': ("))
    for route in compiled["retakes"]["B_to_A"]:
        lines.append(f"        {{'name': {route['name']!r}, 'sha256': {route['sha256']!r}, 'frames': _frames(")
        lines.extend(_payload_lines(_encode_frames(route["frames"]), "            "))
        lines.append("        )},")
    lines.extend(("    ),", "}"))
    output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("static_map", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    write_module(compile_manifest(args.manifest,
                                  json.loads(args.static_map.read_text())), args.output)
